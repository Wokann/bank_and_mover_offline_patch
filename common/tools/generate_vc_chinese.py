"""Generate only character mappings from pinned public translation data.

仅生成固定版本公开汉化码表；不下载 ROM、补丁、字体图像或执行上游工具。
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request
import http.client

ROOT=Path(__file__).resolve().parents[2]
SOURCES={
    'us':('pokecrystal_cn','f487d44c0d6f75a48a4a4b975ca04bc3914b3f52','constants/charmap_cn.asm'),
    'ko':('PKMN_GSCHS','c3947b83c6c66a015103e1bc08bbca7f2a862d3b','05_Font/fontTBL.txt'),
}

def fetch(kind,cache):
    repo,revision,path=SOURCES[kind]
    target=cache/(kind+'.txt')
    if target.is_file():return target.read_bytes()
    error=None
    for _ in range(3):
        try:
            raw_url=f'https://raw.githubusercontent.com/TomJinW/{repo}/{revision}/{path}'
            request=urllib.request.Request(raw_url,headers={'User-Agent':'BankMover-character-table-builder'})
            raw=urllib.request.urlopen(request,timeout=15).read()
            assert raw and len(raw)>500
            cache.mkdir(parents=True,exist_ok=True);target.write_bytes(raw)
            return raw
        except (OSError,ValueError,AssertionError,http.client.IncompleteRead) as exc:error=exc
    raise error

def mapping(kind,raw):
    text=raw.decode('utf-16' if raw.startswith((b'\xff\xfe',b'\xfe\xff')) else 'utf-8-sig');result={}
    if kind=='us':
        rows=[(int(a,16)*256+int(b,16),value) for value,a,b in re.findall(
            r'^\s*charmap_w\s+"([^"]+)",\s*\$([\da-fA-F]+),\s*\$([\da-fA-F]+)',text,re.M)]
    else:
        rows=[(int(key,16),value) for key,value in re.findall(r'^([\da-fA-F]{4})=(.*)$',text,re.M)]
    for key,value in rows:
        if len(value)!=1:continue
        point=ord(value)
        if key in result and result[key]!=point:raise ValueError(('conflicting mapping',kind,hex(key)))
        assert key>255 and point<0x10000 and not 0xd800<=point<=0xdfff
        result[key]=point
    assert len(result)>500
    return result

def generated(kind,values):
    maximum=max(values)
    rows=['/* Generated by common/tools/generate_vc_chinese.py; pinned source in vc_chinese_sources.json. */',
          '/* 由公开汉化码表机械生成，来源与摘要见 vc_chinese_sources.json。 */',
          f'static const u16 chinese_{kind}[0x{maximum+1:x}]={{']
    for start in range(0,maximum+1,16):
        rows.append('    '+','.join(f'0x{values.get(key,0):04x}' for key in range(start,min(start+16,maximum+1)))+',')
    rows+=['};','']
    return '\n'.join(rows)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();cache=ROOT/'bank/build/vc_chinese_sources';manifest={}
    for kind,(repo,revision,path) in SOURCES.items():
        raw=fetch(kind,cache);values=mapping(kind,raw)
        content=generated(kind,values)
        target=ROOT/f'mover/include/vc_chinese_{kind}.inc'
        if args.check:assert target.read_text(encoding='utf-8')==content,('stale generated table',kind)
        else:target.write_text(content,encoding='utf-8',newline='\n')
        manifest[kind]=dict(repository=f'https://github.com/TomJinW/{repo}',revision=revision,path=path,
            url=f'https://raw.githubusercontent.com/TomJinW/{repo}/{revision}/{path}',
            sha256=hashlib.sha256(raw).hexdigest(),entries=len(values),table_bytes=2*(max(values)+1))
        print(kind,manifest[kind],flush=True)
    target=Path(__file__).with_name('vc_chinese_sources.json')
    content=json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'
    if args.check:assert target.read_text(encoding='utf-8')==content
    else:target.write_text(content,encoding='utf-8',newline='\n')

if __name__=='__main__':main()

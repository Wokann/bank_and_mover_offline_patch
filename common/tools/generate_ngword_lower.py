"""Emit the compact BMP lowercase table; never run during a game/build.

UnicodeData supplies simple lowercase, SpecialCasing supplies unconditional
overrides. Per-UTF-16-unit conversion intentionally leaves surrogate pairs
unchanged, as does the public NGWord reference's value[i].toLowerCase().
No locale- or surrounding-text-dependent transformations are applied.
"""
import argparse
from pathlib import Path
import urllib.request
import sys

sys.stdout.reconfigure(encoding='utf-8')

VERSION = '17.0.0'
BASE = f'https://www.unicode.org/Public/{VERSION}/ucd/'


def generate(data, special):
    mapping = {}
    for line in data.splitlines():
        row = line.split(';')
        value = int(row[0], 16)
        if value <= 0xffff and row[13]:
            mapping[value] = (int(row[13], 16),)
    for line in special.splitlines():
        row = line.partition('#')[0].strip().split(';')
        if len(row) < 5 or row[4].strip():
            continue
        value = int(row[0], 16)
        if value <= 0xffff:
            mapping[value] = tuple(int(c, 16) for c in row[1].split())
    mapping = {k: v for k, v in mapping.items() if v != (k,)}
    assert {k: v for k, v in mapping.items() if len(v) > 1} == {0x130: (0x69, 0x307)}
    assert all(v and all(c <= 0xffff for c in v) for v in mapping.values())
    items = sorted((k, v[0]) for k, v in mapping.items() if k > 0xff)
    ranges = []
    i = 0
    while i < len(items):
        first, target = items[i]
        end, step = i + 1, 1
        if end < len(items) and items[end][0] - first in (1, 2) and items[end][1] - items[end][0] == target - first:
            step = items[end][0] - first
            while end < len(items) and items[end][0] - items[end-1][0] == step and items[end][1] - items[end][0] == target - first:
                end += 1
        ranges.append((first, items[end-1][0], target, step))
        i = end
    text = ('/* SPDX-License-Identifier: Unicode-3.0\n'
            '   Copyright (c) 1991-2026 Unicode, Inc.; see common/tools/LICENSE.unicode.txt.\n'
            '   Generated by common/tools/generate_ngword_lower.py; Unicode 17.0.0.\n'
            '   Sources: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt\n'
            '            https://www.unicode.org/Public/17.0.0/ucd/SpecialCasing.txt\n'
            '   U+0130 additionally appends U+0307 in nameViews.\n'
            '   Columns: first, last, lowercase(first), stride (1 or 2).\n'
            '   Generated data only; no runtime file or Unicode library. */\n'
            '/* 自动生成的 BMP 小写映射；无运行时文件读取或 Unicode 库依赖。 */\n'
            'static const uint16_t lowerRanges[][4]={\n')
    text += ''.join('    {0x%04x,0x%04x,0x%04x,%d},\n' % row for row in ranges)
    return text + '};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucd', type=Path, help='optional local directory containing UnicodeData.txt and SpecialCasing.txt')
    parser.add_argument('--patch', action='store_true', help='emit an apply_patch addition instead of C text')
    args = parser.parse_args()
    def read(name):
        if args.ucd:
            return (args.ucd / name).read_text(encoding='utf-8')
        return urllib.request.urlopen(BASE + name, timeout=30).read().decode('utf-8')
    text = generate(read('UnicodeData.txt'), read('SpecialCasing.txt'))
    if args.patch:
        print('*** Begin Patch\n*** Add File: common/src/fakeServer/word_lower.inc')
        print(''.join('+' + line + '\n' for line in text.splitlines()), end='')
        print('*** End Patch')
    else:
        print(text, end='')


if __name__ == '__main__':
    main()
